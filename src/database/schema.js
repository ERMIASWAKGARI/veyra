export const CREATE_TABLES_SQL = `
CREATE TABLE IF NOT EXISTS media_items (
  id TEXT PRIMARY KEY,
  uri TEXT NOT NULL UNIQUE,
  type TEXT NOT NULL, -- 'audio' | 'video'
  title TEXT NOT NULL,
  artist TEXT,
  album TEXT,
  albumArtist TEXT,
  genre TEXT,
  duration INTEGER DEFAULT 0,
  size INTEGER DEFAULT 0,
  mimeType TEXT,
  year INTEGER,
  trackNumber INTEGER,
  discNumber INTEGER,
  artworkUri TEXT,
  folder TEXT,
  dateAdded INTEGER,
  dateModified INTEGER
);

CREATE INDEX IF NOT EXISTS idx_media_type ON media_items (type);
CREATE INDEX IF NOT EXISTS idx_media_artist ON media_items (artist);
CREATE INDEX IF NOT EXISTS idx_media_album ON media_items (album);
CREATE INDEX IF NOT EXISTS idx_media_folder ON media_items (folder);
CREATE INDEX IF NOT EXISTS idx_media_title ON media_items (title);

CREATE TABLE IF NOT EXISTS artists (
  id TEXT PRIMARY KEY,
  name TEXT UNIQUE NOT NULL,
  trackCount INTEGER DEFAULT 0,
  albumCount INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS albums (
  id TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  artist TEXT,
  trackCount INTEGER DEFAULT 0,
  year INTEGER,
  artworkUri TEXT
);

CREATE TABLE IF NOT EXISTS folders (
  id TEXT PRIMARY KEY,
  path TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  mediaCount INTEGER DEFAULT 0,
  type TEXT
);

CREATE TABLE IF NOT EXISTS playlists (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  createdAt INTEGER NOT NULL,
  updatedAt INTEGER NOT NULL,
  itemCount INTEGER DEFAULT 0,
  isAutoGenerated INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS playlist_items (
  id TEXT PRIMARY KEY,
  playlistId TEXT NOT NULL,
  mediaId TEXT NOT NULL,
  sortOrder INTEGER NOT NULL,
  addedAt INTEGER NOT NULL,
  FOREIGN KEY (playlistId) REFERENCES playlists(id) ON DELETE CASCADE,
  FOREIGN KEY (mediaId) REFERENCES media_items(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_playlist_items_pid ON playlist_items (playlistId, sortOrder);

CREATE TABLE IF NOT EXISTS favorites (
  mediaId TEXT PRIMARY KEY,
  type TEXT NOT NULL, -- 'audio' | 'video'
  addedAt INTEGER NOT NULL,
  FOREIGN KEY (mediaId) REFERENCES media_items(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS play_history (
  id TEXT PRIMARY KEY,
  mediaId TEXT NOT NULL,
  playedAt INTEGER NOT NULL,
  position INTEGER DEFAULT 0,
  completionPercentage REAL DEFAULT 0.0,
  FOREIGN KEY (mediaId) REFERENCES media_items(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_history_playedAt ON play_history (playedAt DESC);

CREATE TABLE IF NOT EXISTS playback_state (
  mediaId TEXT PRIMARY KEY,
  position INTEGER DEFAULT 0,
  duration INTEGER DEFAULT 0,
  updatedAt INTEGER NOT NULL,
  speed REAL DEFAULT 1.0,
  isVideo INTEGER DEFAULT 0,
  FOREIGN KEY (mediaId) REFERENCES media_items(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);
`
